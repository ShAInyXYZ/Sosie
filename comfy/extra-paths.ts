// Write comfy/extra_model_paths.yaml from config: every folder of the shared model store
// becomes a model folder of Sosie's ComfyUI (read-only use; nothing is copied).
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { ROOT, loadConfig } from '../server/config.ts'

/** Folders ComfyUI knows under two names. */
const ALIASES: Record<string, string[]> = {
  diffusion_models: ['unet'],
  unet: ['diffusion_models'],
  text_encoders: ['clip'],
  clip: ['text_encoders'],
}

export function extraPathsYaml(store: string, folders: string[]): string {
  const keys = new Map<string, string[]>()
  for (const folder of folders) {
    for (const key of [folder, ...(ALIASES[folder] ?? [])]) {
      keys.set(key, [...(keys.get(key) ?? []), folder])
    }
  }
  const lines = ['# Generated by comfy/extra-paths.ts from config/sosie.local.json. Do not edit.', 'sosie_store:', `  base_path: ${JSON.stringify(store)}`]
  for (const [key, dirs] of [...keys].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`  ${key}: |`)
    for (const dir of [...new Set(dirs)]) lines.push(`    ${dir}`)
  }
  return `${lines.join('\n')}\n`
}

const isMain = process.argv[1]?.endsWith('extra-paths.ts')
if (isMain) {
  const { paths } = loadConfig()
  if (!paths.modelStore || !existsSync(paths.modelStore)) {
    console.error('paths.modelStore is not set or missing in config/sosie.local.json')
    process.exit(1)
  }
  const folders = readdirSync(paths.modelStore).filter((name) => {
    try {
      return statSync(join(paths.modelStore, name)).isDirectory() && !name.startsWith('.')
    } catch {
      return false
    }
  })
  const out = join(ROOT, 'comfy', 'extra_model_paths.yaml')
  writeFileSync(out, extraPathsYaml(paths.modelStore, folders))
  console.log(`wrote ${out} (${folders.length} folders)`)
}
